// Render local staging templates for hosts with the same installation path.
import assert from 'node:assert/strict';
import { mkdirSync, readFileSync, writeFileSync, existsSync, lstatSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const args = process.argv.slice(2);
const options = {};
for (let i = 0; i < args.length; i += 2) {
  assert.ok(['--project', '--user', '--primary', '--standby','--tls-cert','--local'].includes(args[i]) && args[i + 1] && !Object.hasOwn(options, args[i]),
    'Usage: render-deploy.mjs --project /opt/omniroute-ha --user omniroute --primary host-a:20128 --standby host-b:20128');
  options[args[i]] = args[i + 1];
}
const project = options['--project'], user = options['--user'];
assert.ok(typeof project === 'string' && /^\/[a-zA-Z0-9_./-]+$/.test(project) && project !== '/' && path.normalize(project) === project, 'Expected normalized absolute project path');
assert.ok(typeof user === 'string' && /^[a-z_][a-z0-9_-]*$/.test(user) && user !== 'root', 'Expected an unprivileged service user');
function endpoint(value) {
  assert.ok(typeof value === 'string' && /^[a-zA-Z0-9.:[\]-]+$/.test(value), 'Invalid endpoint');
  const url = new URL('tcp://' + value);
  assert.ok(url.hostname && Number.isInteger(Number(url.port)) && Number(url.port) > 0 && Number(url.port) <= 65535 && !url.pathname && !url.username && !url.password, 'Expected host:port');
  return url;
}
const primary = endpoint(options['--primary']), standby = endpoint(options['--standby']);
const local = options['--local'] === 'yes';
assert.ok(!options['--local'] || local, 'Use --local yes only for loopback evaluation');
if(local) assert.ok(primary.hostname==='127.0.0.1'&&standby.hostname==='127.0.0.1'&&primary.port!==standby.port,'Use two distinct loopback ports');
else assert.notEqual(primary.hostname, standby.hostname, 'Two-host deployment requires distinct hostnames');
const directory = path.join(root, '.work/deploy');
mkdirSync(directory, { recursive: true, mode: 0o700 });
assert.ok(lstatSync(directory).isDirectory() && !lstatSync(directory).isSymbolicLink(), 'Refusing a redirected output directory');
const marker = '# Generated by scripts/render-deploy.mjs; staging only.\n';
const unit = readFileSync(path.join(root, 'deploy/omniroute-ha.service.in'), 'utf8')
  .replaceAll('@PROJECT@', project).replaceAll('@SERVICE_USER@', user);
let haproxy = readFileSync(path.join(root, 'deploy/haproxy.cfg'), 'utf8')
  .replaceAll('${OMNI_PRIMARY}', options['--primary']).replaceAll('${OMNI_STANDBY}', options['--standby']);
if(options['--tls-cert']){
  const certificate=options['--tls-cert'];assert.ok(/^\/[a-zA-Z0-9_./-]+$/.test(certificate)&&path.normalize(certificate)===certificate&&certificate.startsWith(project+'/'),'TLS certificate must have a normalized project-local path');
  haproxy=haproxy.replace('bind :8080','bind :8443 ssl crt '+certificate+' ssl-min-ver TLSv1.2').replace('    default_backend omniroute_hosts','    http-request set-header X-Forwarded-Proto https\n    http-request set-header X-Forwarded-For %[src]\n    default_backend omniroute_hosts');
}
if(local)haproxy=haproxy.replace('bind :','bind 127.0.0.1:');
const env = readFileSync(path.join(root, 'deploy/host.env.example'), 'utf8').replaceAll('/opt/omniroute-ha', project);
const hostEnv=(label,address,index)=>env.replace('HOST=0.0.0.0',local?'HOST=127.0.0.1':'HOST=0.0.0.0').replace('PORT=20128','PORT='+address.port).replace('# HA_STATUS_URL=http://host-a.private:20128','HA_STATUS_URL=http://'+address.host)
  .replaceAll(project+'/.work/data',project+'/.work/data-'+index)
  .replace('HA_REDIS_MODE=disabled','HA_REDIS_MODE=sentinel\nHA_REDIS_NODES=[{"host":"sentinel-a.private","port":26379},{"host":"sentinel-b.private","port":26379},{"host":"sentinel-c.private","port":26379}]\nHA_REDIS_MASTER=staging-cache\nHA_REDIS_PASSWORD=')+'\n# Independent '+label+' installation; runtime paths are local, never shared.\n';
for (const [name, content] of [['omniroute-ha.service', unit], ['haproxy.cfg', haproxy], ['host.env.example', env],['host-a.env.example',hostEnv('Host A',primary,'a')],['host-b.env.example',hostEnv('Host B',standby,'b')]]) {
  assert.ok(!/@PROJECT@|@SERVICE_USER@|\$\{OMNI_(?:PRIMARY|STANDBY)\}/.test(content), 'Unresolved deployment placeholder');
  const destination = path.join(directory, name);
  if (existsSync(destination)) {
    assert.ok(lstatSync(destination).isFile() && !lstatSync(destination).isSymbolicLink(), 'Refusing redirected output');
    assert.ok(readFileSync(destination, 'utf8').startsWith(marker), 'Refusing to overwrite a non-generated file');
  }
  writeFileSync(destination, marker + content, { mode: 0o600 });
}
console.log('RENDERED .work/deploy for two distinct hosts; templates only, no remote connections or installed services');
console.log('Configure private host.env secrets and the isolated database on both hosts before starting; HAProxy/systemd execution and independent-host validation remain pending');
